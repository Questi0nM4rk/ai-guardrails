// Feeds bench/corpus.jsonl through the compiled hook binary the way Claude Code does
// (JSON on stdin, HOOK_KIT_ASKPASS empty) and compares the decision with the label
// written before the first run. Deterministic: one run is the measurement.
// Usage: bun bench/hook-corpus.ts   (needs `bun run build:hk-cc` first)

import { existsSync } from "node:fs";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const BIN = join(ROOT, "dist", "ai-guardrails-hk-cc-tools");
const CORPUS = join(import.meta.dir, "corpus.jsonl");
const RESULTS = join(import.meta.dir, "RESULTS.md");

type Decision = "allow" | "ask" | "deny";

interface Row {
  id: number;
  category: string;
  expected: "ask" | "allow";
  event: "PreToolUse" | "PostToolUse";
  tool: string;
  input: Record<string, unknown>;
}

interface Result extends Row {
  actual: Decision;
  raw: string;
}

if (!existsSync(BIN)) {
  process.stderr.write(`bench: ${BIN} is missing, run \`bun run build:hk-cc\` first\n`);
  process.exit(2);
}

// PostToolUse rules read the file from disk, as they do after Claude Code ran the tool.
// Write puts its content there; Edit leaves the edited text (new_string) there.
async function materialize(row: Row, dir: string): Promise<Record<string, unknown>> {
  const input = { ...row.input };
  const fp = input.file_path;
  if (row.event !== "PostToolUse" || typeof fp !== "string") return input;
  const real = fp.replace("/repo", dir);
  input.file_path = real;
  await mkdir(dirname(real), { recursive: true });
  const body = row.tool === "Write" ? String(input.content) : String(input.new_string);
  await writeFile(real, body);
  return input;
}

async function fire(row: Row, dir: string): Promise<Result> {
  const event = {
    hook_event_name: row.event,
    session_id: "bench",
    cwd: dir,
    transcript_path: join(dir, "transcript"),
    tool_name: row.tool,
    tool_input: await materialize(row, dir),
    ...(row.event === "PostToolUse" ? { tool_response: {} } : {}),
  };
  const proc = Bun.spawn([BIN], {
    stdin: new Response(JSON.stringify(event)),
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, HOOK_KIT_ASKPASS: "" },
  });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  const raw = stdout.trim() || stderr.trim();
  let actual: Decision = "allow";
  if (stdout.trim() !== "") {
    const out = JSON.parse(stdout);
    const d = out.hookSpecificOutput?.permissionDecision;
    // PostToolUse cannot "ask"; the hook degrades it to context for the model, which is a flag.
    actual = d === "deny" ? "deny" : "ask";
  } else if (exitCode !== 0) {
    actual = "deny";
  }
  return { ...row, actual, raw };
}

const rows: Row[] = (await Bun.file(CORPUS).text())
  .split("\n")
  .filter((l) => l.trim() !== "")
  .map((l) => JSON.parse(l));

const dir = await mkdtemp(join(ROOT, "bench", ".work-"));
const results: Result[] = [];
try {
  for (const row of rows) results.push(await fire(row, dir));
} finally {
  await rm(dir, { recursive: true, force: true });
}

const flagged = (r: Result) => r.actual !== "allow";
const dangerous = results.filter((r) => r.expected === "ask");
const benign = results.filter((r) => r.expected === "allow");
const misses = dangerous.filter((r) => !flagged(r));
const falseAsks = benign.filter(flagged);

const label = (r: Result) =>
  r.tool === "Bash"
    ? String(r.input.command)
    : `${r.event} ${r.tool} ${String(r.input.file_path)} ${String(r.input.content ?? r.input.new_string ?? "").split("\n")[0]}`.trim();
const cell = (s: string) => `\`${s.replaceAll("|", "\\|").replaceAll("\n", "\\n")}\``;

const lines = [
  "# Hook decisions on a labelled corpus",
  "",
  "Generated by `bun bench/hook-corpus.ts` through `dist/ai-guardrails-hk-cc-tools`. Labels were written before the first run and not changed after it.",
  "",
  `- Caught dangerous: ${dangerous.length - misses.length} / ${dangerous.length}`,
  `- False asks on benign: ${falseAsks.length} / ${benign.length}`,
  "",
  "## Misses (dangerous, not flagged)",
  "",
  "| # | Category | Input |",
  "| --- | --- | --- |",
  ...misses.map((r) => `| ${r.id} | ${r.category} | ${cell(label(r))} |`),
  "",
  "## False asks (benign, flagged)",
  "",
  "| # | Category | Input | Reason |",
  "| --- | --- | --- | --- |",
  ...falseAsks.map(
    (r) =>
      `| ${r.id} | ${r.category} | ${cell(label(r))} | ${cell(r.raw.slice(0, 120))} |`
  ),
  "",
  "## By category (caught or correctly allowed / total)",
  "",
  "| Category | Expected | OK / total |",
  "| --- | --- | --- |",
  ...[...new Set(results.map((r) => r.category))].map((c) => {
    const rs = results.filter((r) => r.category === c);
    const ok = rs.filter((r) => flagged(r) === (r.expected === "ask")).length;
    return `| ${c} | ${rs[0]?.expected} | ${ok} / ${rs.length} |`;
  }),
  "",
];
await Bun.write(RESULTS, lines.join("\n"));

process.stdout.write(
  `caught ${dangerous.length - misses.length}/${dangerous.length}, false asks ${falseAsks.length}/${benign.length}, misses ${misses.length}\n`
);
for (const r of misses)
  process.stdout.write(`MISS #${r.id} [${r.category}] ${label(r)}\n`);
for (const r of falseAsks)
  process.stdout.write(`FALSE-ASK #${r.id} [${r.category}] ${label(r)}\n`);
